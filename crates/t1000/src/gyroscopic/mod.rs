//! 8-Node Gyroscopic Throwing-Jack & Wobbling Pulsar Stabilizer Engine
//!
//! Models the physical mechanics of a 6-pronged throwing jack whose axes
//! intersect at a solid center of mass Node (4, 5), alongside a double-ended
//! precessing pulsar with counter-phase torque cancellation and decoherence-free
//! quantum phase-locking.

pub mod mechanics;
pub mod quantum_lock;
pub mod topology;

pub use mechanics::{GyroMechanicsEngine, MechanicsStep};
pub use quantum_lock::{QuantumLockEngine, QuantumLockStep};
pub use topology::{JackNode, JackTopology, Vector3D};

use serde::{Deserialize, Serialize};

/// Configuration parameters for the gyroscopic stabilizer simulation.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct GyroscopicConfig {
    pub arm_length: f64,
    pub precession_freq_rad_s: f64,
    pub noise_freq_rad_s: f64,
    pub noise_amplitude_n: f64,
    pub quantum_noise_amplitude_rad: f64,
    pub core_coupling_strength_g: f64,
    pub total_time_s: f64,
    pub steps: usize,
}

impl Default for GyroscopicConfig {
    fn default() -> Self {
        Self {
            arm_length: 1.5,
            precession_freq_rad_s: 120.0,
            noise_freq_rad_s: 45.0,
            noise_amplitude_n: 2.5,
            quantum_noise_amplitude_rad: 1.25,
            core_coupling_strength_g: 0.85,
            total_time_s: 1.0,
            steps: 100,
        }
    }
}

/// Comprehensive telemetry report generated by the gyroscopic stabilizer engine.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct GyroscopicReport {
    pub config: GyroscopicConfig,
    pub initial_topology: JackTopology,
    pub final_topology: JackTopology,
    pub mechanics_steps: Vec<MechanicsStep>,
    pub quantum_steps: Vec<QuantumLockStep>,
    pub mean_torque_cancellation_ratio: f64,
    pub max_torque_net_norm: f64,
    pub min_core_fidelity: f64,
    pub mean_parity_correlator: f64,
    pub max_center_of_mass_drift: f64,
    pub mean_gyroscopic_q_factor: f64,
}

/// The master gyroscopic stabilizer engine.
#[derive(Debug, Clone, Default)]
pub struct GyroscopicStabilizerEngine;

impl GyroscopicStabilizerEngine {
    pub fn new() -> Self {
        Self
    }

    /// Executes the full kinetic, classical, and quantum simulation of the 8-node stabilizer.
    pub fn simulate(&self, config: &GyroscopicConfig) -> GyroscopicReport {
        let mut topology = JackTopology::new(config.arm_length);
        let initial_topology = topology.clone();

        let mechanics_engine = GyroMechanicsEngine::new(
            config.precession_freq_rad_s,
            config.noise_freq_rad_s,
            config.noise_amplitude_n,
        );

        let quantum_engine = QuantumLockEngine::new(
            config.quantum_noise_amplitude_rad,
            config.noise_freq_rad_s,
            config.core_coupling_strength_g,
        );

        let dt = config.total_time_s / (config.steps as f64).max(1.0);
        let mut mechanics_steps = Vec::with_capacity(config.steps);
        let mut quantum_steps = Vec::with_capacity(config.steps);

        let mut sum_cancellation = 0.0_f64;
        let mut max_tau_net = 0.0_f64;
        let mut min_fid = 1.0_f64;
        let mut sum_parity = 0.0_f64;
        let mut max_com_drift = 0.0_f64;
        let mut sum_q_factor = 0.0_f64;

        for step_idx in 0..=config.steps {
            let t = step_idx as f64 * dt;
            let m_step = mechanics_engine.step(&mut topology, t);
            let q_step = quantum_engine.evaluate_step(t);

            sum_cancellation += m_step.torque_cancellation_ratio;
            max_tau_net = max_tau_net.max(m_step.torque_net.norm());
            min_fid = min_fid.min(q_step.core_fidelity);
            sum_parity += q_step.parity_correlator_zab;
            max_com_drift = max_com_drift.max(m_step.center_of_mass_drift);
            sum_q_factor += q_step.gyroscopic_q_factor;

            mechanics_steps.push(m_step);
            quantum_steps.push(q_step);
        }

        let num_evals = (config.steps + 1) as f64;

        GyroscopicReport {
            config: config.clone(),
            initial_topology,
            final_topology: topology,
            mechanics_steps,
            quantum_steps,
            mean_torque_cancellation_ratio: sum_cancellation / num_evals,
            max_torque_net_norm: max_tau_net,
            min_core_fidelity: min_fid,
            mean_parity_correlator: sum_parity / num_evals,
            max_center_of_mass_drift: max_com_drift,
            mean_gyroscopic_q_factor: sum_q_factor / num_evals,
        }
    }
}
